import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { Subscription, Customer, Plan, Invoice, PaymentTransaction, AppUser } from '../types';

interface SubscriptionReportOptions {
  subscriptions: Subscription[];
  plans: Plan[];
  totalMrr: number;
  totalArr: number;
  activeCount: number;
  currency: string;
  formatCurrency: (amount: number) => string;
  adminUser: AppUser | null;
  periodLabel?: string;
  statusFilter?: string;
}

interface RevenueReportOptions {
  totalMrr: number;
  totalArr: number;
  currency: string;
  formatCurrency: (amount: number) => string;
  adminUser: AppUser | null;
  invoices: Invoice[];
  payments: PaymentTransaction[];
  periodLabel?: string;
}

const BRAND_NAVY = [10, 17, 40] as [number, number, number]; // #0A1128
const BRAND_BLUE = [37, 99, 235] as [number, number, number]; // #2563EB
const BRAND_SLATE = [71, 85, 105] as [number, number, number]; // #475569
const LIGHT_BG = [248, 250, 252] as [number, number, number];

export const generateSubscriptionReportPDF = ({
  subscriptions,
  plans,
  totalMrr,
  totalArr,
  activeCount,
  currency,
  formatCurrency,
  adminUser,
  periodLabel = 'Current Billing Period',
  statusFilter = 'All'
}: SubscriptionReportOptions) => {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const todayStr = new Date().toISOString().replace('T', ' ').substring(0, 19);
  const auditId = `BL-SUB-${Math.random().toString(36).substring(2, 8).toUpperCase()}-${Date.now().toString().slice(-4)}`;

  // Header Banner
  doc.setFillColor(...BRAND_NAVY);
  doc.rect(0, 0, pageWidth, 28, 'F');

  // Brand Name & Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(255, 255, 255);
  doc.text('BRIGHTLOOP', 14, 12);

  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(147, 197, 253);
  doc.text('SaaS Subscription & Billing Engine · Administrator Audit Report', 14, 18);

  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(255, 255, 255);
  doc.text('SUBSCRIPTION AUDIT REPORT', pageWidth - 14, 12, { align: 'right' });

  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225);
  doc.text(`Scope: ${statusFilter.toUpperCase()} | ${periodLabel}`, pageWidth - 14, 18, { align: 'right' });

  // Administrator Audit Bar
  doc.setFillColor(...LIGHT_BG);
  doc.rect(14, 32, pageWidth - 28, 16, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.rect(14, 32, pageWidth - 28, 16, 'S');

  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...BRAND_NAVY);
  doc.text('ADMINISTRATOR VERIFICATION & AUDIT TRAIL', 18, 38);

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...BRAND_SLATE);
  const adminName = adminUser ? `${adminUser.name} (${adminUser.role})` : 'System Administrator (ADMIN)';
  const adminDept = adminUser?.department ? ` · Dept: ${adminUser.department}` : '';
  doc.text(`Generated by: ${adminName}${adminDept} | Audit ID: ${auditId} | Generated: ${todayStr}`, 18, 43);

  // Executive KPI Summary Boxes
  const boxWidth = (pageWidth - 28 - 9) / 4;
  const kpis = [
    { label: 'ACTIVE SUBSCRIPTIONS', val: activeCount.toString(), sub: 'Paying accounts' },
    { label: 'MONTHLY RUN RATE (MRR)', val: formatCurrency(totalMrr), sub: `${currency} recurring/mo` },
    { label: 'ANNUAL RUN RATE (ARR)', val: formatCurrency(totalArr), sub: 'Annualized revenue' },
    { label: 'AVG REVENUE / SUB', val: formatCurrency(activeCount > 0 ? Math.round(totalMrr / activeCount) : 0), sub: 'ARPU metric' }
  ];

  kpis.forEach((kpi, i) => {
    const x = 14 + i * (boxWidth + 3);
    doc.setFillColor(255, 255, 255);
    doc.rect(x, 52, boxWidth, 18, 'F');
    doc.setDrawColor(203, 213, 225);
    doc.rect(x, 52, boxWidth, 18, 'S');

    doc.setFontSize(6.5);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...BRAND_SLATE);
    doc.text(kpi.label, x + 3, 57);

    doc.setFontSize(10.5);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...BRAND_NAVY);
    doc.text(kpi.val, x + 3, 63);

    doc.setFontSize(6.5);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100, 116, 139);
    doc.text(kpi.sub, x + 3, 68);
  });

  // Section 1: Tier Distribution Table
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...BRAND_NAVY);
  doc.text('1. SUBSCRIPTION TIER DISTRIBUTION', 14, 76);

  const tierRows = plans.map(p => {
    const matchingSubs = subscriptions.filter(s => s.planId === p.id && s.status === 'active');
    const planMrr = matchingSubs.reduce((acc, s) => acc + (s.billingCycle === 'annual' ? Math.round(s.amount / 12) : s.amount), 0);
    const pctOfTotal = totalMrr > 0 ? ((planMrr / totalMrr) * 100).toFixed(1) + '%' : '0%';
    return [
      p.name,
      p.tierCode,
      matchingSubs.length.toString(),
      formatCurrency(p.priceMonthly),
      formatCurrency(planMrr),
      pctOfTotal,
      p.status.toUpperCase()
    ];
  });

  autoTable(doc, {
    startY: 79,
    head: [['Plan Tier', 'Tier Code', 'Active Subs', 'Base Monthly', 'Contributed MRR', '% of MRR', 'Catalog Status']],
    body: tierRows,
    theme: 'grid',
    headStyles: {
      fillColor: BRAND_NAVY,
      textColor: [255, 255, 255],
      fontSize: 7.5,
      fontStyle: 'bold'
    },
    bodyStyles: {
      fontSize: 7,
      textColor: [30, 41, 59]
    },
    columnStyles: {
      0: { fontStyle: 'bold' },
      2: { halign: 'center' },
      3: { halign: 'right' },
      4: { halign: 'right', fontStyle: 'bold' },
      5: { halign: 'center' },
      6: { halign: 'center' }
    },
    styles: { cellPadding: 2 }
  });

  // Section 2: Detailed Subscription Ledger
  const currentY = (doc as any).lastAutoTable.finalY + 8;
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...BRAND_NAVY);
  doc.text('2. INDIVIDUAL SUBSCRIPTION CONTRACT LEDGER', 14, currentY);

  const subRows = subscriptions.map(s => [
    s.id,
    s.customerName,
    s.company,
    s.planName,
    s.status.toUpperCase().replace('_', ' '),
    s.billingCycle.toUpperCase(),
    formatCurrency(s.amount),
    s.renewalDate,
    s.autoRenew ? 'YES' : 'NO'
  ]);

  autoTable(doc, {
    startY: currentY + 3,
    head: [['Sub ID', 'Customer Name', 'Company', 'Plan', 'Status', 'Cycle', 'Amount', 'Renewal Date', 'Auto-Renew']],
    body: subRows,
    theme: 'striped',
    headStyles: {
      fillColor: BRAND_BLUE,
      textColor: [255, 255, 255],
      fontSize: 7.5,
      fontStyle: 'bold'
    },
    bodyStyles: {
      fontSize: 6.8,
      textColor: [30, 41, 59]
    },
    columnStyles: {
      0: { fontStyle: 'bold' },
      4: { halign: 'center', fontStyle: 'bold' },
      5: { halign: 'center' },
      6: { halign: 'right', fontStyle: 'bold' },
      7: { halign: 'center' },
      8: { halign: 'center' }
    },
    styles: { cellPadding: 2.2 }
  });

  // Footer on all pages
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    doc.setDrawColor(226, 232, 240);
    doc.line(14, pageHeight - 12, pageWidth - 14, pageHeight - 12);

    doc.setFontSize(7);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(148, 163, 184);
    doc.text('CONFIDENTIAL & PROPRIETARY · Brightloop Subscription Billing Platform · ASC 606 / GAAP Compliant', 14, pageHeight - 7);
    doc.text(`Page ${i} of ${totalPages}`, pageWidth - 14, pageHeight - 7, { align: 'right' });
  }

  // Save / Trigger Download
  const filename = `brightloop_subscription_report_${new Date().toISOString().split('T')[0]}.pdf`;
  doc.save(filename);
  return filename;
};


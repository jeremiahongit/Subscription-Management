  doc.setTextColor(255, 255, 255);
  doc.text('REVENUE & ASC 606 REPORT', pageWidth - 14, 12, { align: 'right' });

  doc.setFontSize(8);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(203, 213, 225);
  doc.text(`Period: ${periodLabel} | GAAP Standard`, pageWidth - 14, 18, { align: 'right' });

  // Administrator Audit Bar
  doc.setFillColor(...LIGHT_BG);
  doc.rect(14, 32, pageWidth - 28, 16, 'F');
  doc.setDrawColor(226, 232, 240);
  doc.rect(14, 32, pageWidth - 28, 16, 'S');

  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(...BRAND_NAVY);
  doc.text('FINANCIAL AUDIT AUTHORIZATION & INTEGRITY STAMP', 18, 38);

  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...BRAND_SLATE);

  doc.text(`Authorized by: ${adminName} | Audit ID: ${auditId} | Certified: ${todayStr}`, 18, 43);

  // Key SaaS Efficiency Metrics
  const boxWidth = (pageWidth - 28 - 9) / 4;
  const metrics = [
    { label: 'ANNUAL RUN RATE (ARR)', val: formatCurrency(totalArr), sub: 'Contracted run-rate' },
    { label: 'MONTHLY RECURRING (MRR)', val: formatCurrency(totalMrr), sub: 'Active recurring' },
    { label: 'NET RETENTION (NRR)', val: '114.2%', sub: 'Net expansion > churn' },
    { label: 'GROSS RETENTION (GRR)', val: '94.8%', sub: 'Elite benchmark' }
  ];

  metrics.forEach((kpi, i) => {
    const x = 14 + i * (boxWidth + 3);
    doc.setFillColor(255, 255, 255);
    doc.rect(x, 52, boxWidth, 18, 'F');
    doc.setDrawColor(203, 213, 225);
    doc.rect(x, 52, boxWidth, 18, 'S');

    doc.setFontSize(6.5);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...BRAND_SLATE);
    doc.text(kpi.label, x + 3, 57);

    doc.setFontSize(10.5);
    doc.setFont('helvetica', 'bold');
    doc.setTextColor(...BRAND_NAVY);
    doc.text(kpi.val, x + 3, 63);

    doc.setFontSize(6.5);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(100, 116, 139);
    doc.text(kpi.sub, x + 3, 68);
  });

